// Terms that must not be translated
const NON_TRANSLATABLE = [
  'Kenntnisprüfung',
  'Approbation',
  'M2',
  'M3',
  'Physikum'
]

function protectTerms(text: string): string {
  return NON_TRANSLATABLE.reduce((acc, term) => acc.replaceAll(term, `{{${term}}}`), text)
}

function restoreTerms(text: string): string {
  return NON_TRANSLATABLE.reduce((acc, term) => acc.replaceAll(`{{${term}}}`, term), text)
}

